"""docs/reference/policy.md, generated from the policy lists in the source, so the page cannot drift from the code.

`python3 tests/policy_tables.py --write` rewrites the page (run in the guest); tests/test_docs.py checks it is current.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from appjail import dbusproxy, grants, portal, seccomp, wayland

PAGE = ROOT / "docs" / "reference" / "policy.md"

SOCKET_FAMILY_NAMES = {0: "AF_UNSPEC", 1: "AF_UNIX", 2: "AF_INET", 10: "AF_INET6", 16: "AF_NETLINK"}


def _codes(items, prefix="", suffix=""):
    return ", ".join(f"`{prefix}{i}{suffix}`" for i in items)


def render():
    out = ["# Policy lists", "",
           "<!-- generated by tests/policy_tables.py from the source; edit the source, then run it with --write -->", "",
           "The exact lists appjail enforces, taken from its source when this page was generated. Why each exists is",
           "explained on the page linked under each heading.", ""]

    out += ["## Paths that are never granted", "",
            "Explained in [the filesystem view](../understand/isolation/filesystem.md). Paths below the home directory",
            "are written without `~/`; a folder that contains one of the secret paths is refused too.", "",
            "| Refused | In every mode | Read-write only |", "|---|---|---|",
            f"| credentials and secrets (`grants.SECRET_HOME_DIRS`) | {_codes(grants.SECRET_HOME_DIRS)} | |",
            f"| file names like keys and password databases (`grants.SECRET_SUFFIXES`) | {_codes(grants.SECRET_SUFFIXES, '*')} | |",
            f"| too broad (`grants.BROAD_HOME_DIRS`) | {_codes(grants.BROAD_HOME_DIRS)}, the home directory and its parents, `/` | |",
            f"| system trees (`grants.SYSTEM_PATHS`) | {_codes(grants.SYSTEM_PATHS)} | |",
            f"| shared temporary directories, as folders (`grants.SHARED_DIRS`) | {_codes(grants.SHARED_DIRS)} | |",
            f"| code that runs outside the jail later (`grants.PERSIST_HOME_DIRS`) | | {_codes(grants.PERSIST_HOME_DIRS)} |",
            f"| startup files (`grants.PERSIST_HOME_FILES`) | | {_codes(grants.PERSIST_HOME_FILES)} |",
            f"| the look of your other apps (`grants.APPEARANCE_HOME_DIRS`) | | {_codes(grants.APPEARANCE_HOME_DIRS)} |",
            ""]

    out += ["## D-Bus names", "",
            "Explained in [D-Bus and the filtering proxy](../understand/desktop/dbus.md).", "",
            "| List | Names |", "|---|---|",
            f"| refused, with every name below them (`grants.DBUS_BLOCKED`) | {_codes(grants.DBUS_BLOCKED)} |",
            f"| allowed with a warning: stored secrets (`grants.DBUS_SENSITIVE`) | {_codes(grants.DBUS_SENSITIVE)} |",
            f"| cannot be owned (`grants.DBUS_NO_OWN`) | {_codes(grants.DBUS_NO_OWN, suffix='*')} |",
            f"| may be owned all the same (`grants.DBUS_OWN_OK`) | {_codes(grants.DBUS_OWN_OK, suffix='*')} |",
            f"| a wildcard needs at least | {grants.DBUS_MIN_WILDCARD_PARTS} name parts before `.*` |",
            "", ("Confined services (`dbusproxy.CONFINED`): only these interfaces, on this object path, plus "
                 f"{_codes(dbusproxy.STANDARD)}."), "",
            "| Name | Interfaces | Object path |", "|---|---|---|"]
    for name, (interfaces, path) in dbusproxy.CONFINED.items():
        out.append(f"| `{name}` | {_codes(interfaces)} | `{path}` |")
    out.append("")

    out += ["## Portal interfaces", "",
            ("Explained in [portals](../understand/desktop/portals.md). Names are the part after "
             "`org.freedesktop.portal.`."), "",
            "| Set | Interfaces |", "|---|---|",
            f"| with `portals = true` (`grants.PORTAL_SAFE`), plus the document portal | {_codes(grants.PORTAL_SAFE)} |",
            f"| opt-in, named in `portal_interfaces` (`grants.PORTAL_OPT_IN`) | {_codes(grants.PORTAL_OPT_IN)} |",
            f"| never (`grants.PORTAL_NEVER`) | {_codes(grants.PORTAL_NEVER)} |",
            f"| permission-store tables cleared by `remove` (`portal.STORE_TABLES`) | {_codes(portal.STORE_TABLES)} |",
            ""]

    out += ["## Wayland interfaces", "",
            "Explained in [Wayland](../understand/desktop/wayland.md). A socket that lists a privileged interface, or one",
            "in neither list, refuses a windowed app without `full_wayland`.", "",
            "| Privileged kind | Lets a client | Interfaces |", "|---|---|---|"]
    for kind, names in wayland.PRIVILEGED.items():
        out.append(f"| {kind} | {wayland.CAPABILITY[kind]} | {_codes(names)} |")
    out += ["", f"Allowed (`wayland.ALLOWED`): {_codes(sorted(wayland.ALLOWED))}.", ""]

    out += ["## System calls", "",
            "Explained in [seccomp](../understand/isolation/seccomp.md).", "",
            "| Rule | System calls |", "|---|---|",
            f"| always refused, `EPERM` (`seccomp.ALWAYS`) | {_codes(seccomp.ALWAYS)} |",
            "| `ioctl` refused, `EPERM` | `TIOCSTI`, `TIOCLINUX` |",
            (f"| `socket`, `socketpair`: only these families, else `EAFNOSUPPORT` | "
             f"{', '.join(f'`{SOCKET_FAMILY_NAMES.get(f, f)}`' for f in seccomp.SOCKET_FAMILIES)} |"),
            "| `personality`: only the default and the query, else `EPERM` | `PER_LINUX`, `0xffffffff` |",
            f"| answered `ENOSYS` (`seccomp.IO_URING`) | {_codes(seccomp.IO_URING)} |",
            (f"| refused without `userns`, `EPERM` (`seccomp.NAMESPACE`) | {_codes(seccomp.NAMESPACE)}, `clone` with a "
             "new-namespace flag; `clone3` answers `ENOSYS` |"),
            "| any architecture but x86-64, the x32 ABI | process killed / `EPERM` |", ""]
    return "\n".join(out)


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        PAGE.write_text(render(), encoding="utf-8")
    else:
        sys.stdout.write(render())
